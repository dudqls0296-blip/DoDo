export function replyUser({ category, worry, summary, chat }) {
  return [
    `카테고리: ${category}`,
    `처음 고민: ${worry}`,
    `고민저장소가 보낸 요약: ${summary}`,
    `대화:`,
    ...chat.map((m) => `${m.role === 'user' ? '사용자' : '고민저장소'}: ${m.text}`),
    `위 대화의 마지막 사용자 말에 답장해줘.`,
  ].join('\n');
}

/** 모델 응답에서 JSON 하나를 꺼낸다 */
export function parseJson(text) {
  if (!text) throw new Error('empty');
  const s = text.indexOf('{');
  const e = text.lastIndexOf('}');
  if (s < 0 || e < s) throw new Error('no json');
  return JSON.parse(text.slice(s, e + 1));
}
