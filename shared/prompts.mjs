export function questionUser({ category, worry, turns, slot }) {
  return [
    `카테고리: ${category}`,
    `사용자의 고민(원문): ${worry}`,
    `지금까지의 문답: ${turns && turns.length ? turns.map((t, i) => `Q${i + 1}. ${t.question} → A. ${t.answer}`).join(' / ') : '(없음)'}`,
    `이번에 만들 slot: ${slot}`,
  ].join('\n');
}

